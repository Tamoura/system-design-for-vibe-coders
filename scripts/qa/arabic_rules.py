#!/usr/bin/env python3
"""The owner's standing rules for Arabic text, as checks.

  mermaid  Every Mermaid flowchart or graph that runs LR in an English source runs RL in its Arabic
           twin, and every 'direction LR' inside it becomes 'direction RL'. Twins are X.md and X.ar.md;
           blocks are compared in order. TB, TD and other diagram types are left alone.
  dpo      Every 'DPO' in Arabic text has the Arabic word for protection (حماية) close by: within 100
           characters before it or 60 after it, on the same line. In today's sources the word is at
           most 63 characters before the token, as in «مسؤولة حماية البيانات (DPO)» or a longer
           gloss such as «أشرِك مسؤول حماية البيانات والفريق القانوني ... (Bring in the DPO ...)».
  gloss    Every Arabic lesson file keeps its English glosses: parenthesised text with Latin letters,
           per 100 Arabic words, is at or above a floor. The floor was set from the lowest lesson on
           the day the check was written, minus a margin (see the baseline file).

Sources: Arabic Markdown files (*.ar.md) that are not generated by a builder, the Arabic fields of the
self-assessment items (<course>/assessment/data/*.json, assessment/data/*.json) and the hand-written
about/index.ar.html. Generated pages repeat these sources, so they are not scanned again. agentic/ is a
published copy of another repository and is not checked.

Violations that already existed when the baseline was written are listed in
scripts/qa/arabic-baseline.json and reported, but only new ones fail the run.

usage:
  python3 scripts/qa/arabic_rules.py                     # report; exit 1 on a violation not in the baseline
  python3 scripts/qa/arabic_rules.py --update-baseline   # accept today's violations (keeps the gloss floor)
  python3 scripts/qa/arabic_rules.py --reset-floor       # with --update-baseline: floor = today's minimum - margin
  python3 scripts/qa/arabic_rules.py --gloss-table       # every lesson's gloss density, lowest first
"""
from __future__ import annotations

import argparse
import json
import math
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASELINE = Path(__file__).resolve().with_name("arabic-baseline.json")
SKIP_DIRS = {"node_modules", "agentic", "beacon", "videos", "dist", "_site", ".git"}
GLOSS_MARGIN = 3.0       # glosses per 100 Arabic words below today's minimum
DPO_BEFORE, DPO_AFTER = 100, 60

FENCE = re.compile(r"^```[^\n]*\n.*?^```[ \t]*$", re.S | re.M)
MERMAID = re.compile(r"^```mermaid[^\n]*\n(.*?)^```", re.S | re.M)
DIAGRAM_HEAD = re.compile(r"^(flowchart|graph)\s+(LR|RL|TB|TD|BT)\b")
DIRECTION = re.compile(r"^\s*direction\s+(LR|RL|TB|TD|BT)\b", re.M)
ARABIC = re.compile(r"[؀-ۿ]")
GLOSS = re.compile(r"\(([^()\n]*[A-Za-z][^()\n]*)\)")
DPO = re.compile(r"\bDPOs?\b")
PROTECTION = "حماية"


def tracked_files() -> list[Path]:
    """Tracked and new (not ignored) files, so the check sees work in progress as CI will see it."""
    try:
        out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
                             cwd=ROOT, capture_output=True, text=True, check=True).stdout
        paths = [ROOT / p for p in out.split("\0") if p]
    except (OSError, subprocess.CalledProcessError):
        paths = [p for p in ROOT.rglob("*") if p.is_file()]
    return [p for p in paths if p.exists() and p.relative_to(ROOT).parts[0] not in SKIP_DIRS]


def generated(path: Path) -> bool:
    with path.open(encoding="utf-8") as fh:
        return "Generated by" in fh.readline()


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def blank_code(text: str) -> str:
    """Remove fenced blocks and inline code, keeping line numbers."""
    text = FENCE.sub(lambda m: "\n" * m.group(0).count("\n"), text)
    return re.sub(r"`[^`\n]*`", " ", text)


# ------------------------------------------------------------------ rule: mermaid direction

def diagram_head(block: str) -> str:
    for line in block.split("\n"):
        s = line.strip()
        if s and not s.startswith("%%"):
            return s
    return ""


def check_mermaid(ar_md: list[Path]) -> list[dict]:
    out = []
    for ar in ar_md:
        en = ar.with_name(ar.name[: -len(".ar.md")] + ".md")
        if not en.exists():
            continue
        be = MERMAID.findall(en.read_text(encoding="utf-8"))
        ba = MERMAID.findall(ar.read_text(encoding="utf-8"))
        if len(be) != len(ba):
            out.append({"rule": "mermaid", "key": f"mermaid|{rel(ar)}|count",
                        "where": rel(ar), "what": f"{len(be)} Mermaid blocks in English, {len(ba)} in Arabic: cannot compare"})
            continue
        for i, (x, y) in enumerate(zip(be, ba), 1):
            mx, my = DIAGRAM_HEAD.match(diagram_head(x)), DIAGRAM_HEAD.match(diagram_head(y))
            if mx and mx.group(2) == "LR" and not (my and my.group(2) == "RL"):
                out.append({"rule": "mermaid", "key": f"mermaid|{rel(ar)}|block {i}",
                            "where": f"{rel(ar)} block {i}", "what": f"English '{diagram_head(x)}' but Arabic '{diagram_head(y)}' (should run RL)"})
            dx, dy = DIRECTION.findall(x), DIRECTION.findall(y)
            for j, d in enumerate(dx):
                if d == "LR" and (j >= len(dy) or dy[j] != "RL"):
                    out.append({"rule": "mermaid", "key": f"mermaid|{rel(ar)}|block {i}|direction {j + 1}",
                                "where": f"{rel(ar)} block {i}", "what": f"subgraph 'direction LR' #{j + 1} is not 'direction RL' in Arabic"})
    return out


# ------------------------------------------------------------------ rule: DPO with حماية

def dpo_hits(text: str, where: str) -> list[dict]:
    out = []
    for lineno, line in enumerate(text.split("\n"), 1):
        for m in DPO.finditer(line):
            before = line[max(0, m.start() - DPO_BEFORE): m.start()]
            after = line[m.end(): m.end() + DPO_AFTER]
            if PROTECTION in before or PROTECTION in after:
                continue
            context = re.sub(r"\s+", " ", line[max(0, m.start() - 40): m.end() + 20]).strip()
            out.append({"rule": "dpo", "key": f"dpo|{where}|{context}", "where": f"{where}:{lineno}",
                        "what": f"'DPO' without {PROTECTION} nearby: …{context}…"})
    return out


def ar_strings(node) -> list[str]:
    """Every string under an 'ar' key in a self-assessment item file."""
    found = []
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "ar":
                found += [v] if isinstance(v, str) else [s for s in v if isinstance(s, str)] if isinstance(v, list) else []
            else:
                found += ar_strings(v)
    elif isinstance(node, list):
        for v in node:
            found += ar_strings(v)
    return found


def check_dpo(ar_md: list[Path], items: list[Path], pages: list[Path]) -> list[dict]:
    out = []
    for f in ar_md:
        out += dpo_hits(blank_code(f.read_text(encoding="utf-8")), rel(f))
    for f in items:
        for s in ar_strings(json.loads(f.read_text(encoding="utf-8"))):
            out += [dict(h, where=rel(f)) for h in dpo_hits(s, rel(f))]
    for f in pages:
        text = re.sub(r"<(script|style)\b.*?</\1>", " ", f.read_text(encoding="utf-8"), flags=re.S | re.I)
        out += dpo_hits(re.sub(r"<[^>]+>", "", text), rel(f))
    return out


# ------------------------------------------------------------------ rule: English glosses

def gloss_density(path: Path) -> tuple[float, int, int]:
    text = blank_code(path.read_text(encoding="utf-8"))
    text = re.sub(r"\]\([^)\s]*\)", "]", text)          # link targets are not glosses
    text = re.sub(r"https?://\S+", " ", text)
    words = sum(1 for w in text.split() if ARABIC.search(w))
    glosses = len(GLOSS.findall(text))
    return (100.0 * glosses / words if words else math.inf), glosses, words


def lesson_files(files: list[Path]) -> list[Path]:
    out = []
    for f in files:
        parts = f.relative_to(ROOT).parts
        if f.name.endswith(".ar.md") and ((len(parts) == 3 and parts[1] == "modules") or (len(parts) == 3 and parts[0] == "modules")):
            out.append(f)
    return sorted(out)


def check_gloss(lessons: list[Path], floor: float) -> tuple[list[dict], list[tuple]]:
    out, table = [], []
    for f in lessons:
        d, g, w = gloss_density(f)
        table.append((d, g, w, rel(f)))
        if d < floor:
            out.append({"rule": "gloss", "key": f"gloss|{rel(f)}", "where": rel(f),
                        "what": f"{d:.1f} English glosses per 100 Arabic words ({g} in {w}); floor {floor:g}"})
    return out, sorted(table)


# ------------------------------------------------------------------ main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--update-baseline", action="store_true", help="accept today's violations as known exceptions")
    ap.add_argument("--reset-floor", action="store_true", help="with --update-baseline: recompute the gloss floor")
    ap.add_argument("--gloss-table", action="store_true", help="print every lesson's gloss density")
    ap.add_argument("--baseline", type=Path, default=BASELINE)
    args = ap.parse_args()

    files = tracked_files()
    ar_md = sorted(f for f in files if f.name.endswith(".ar.md") and not generated(f))
    items = sorted(f for f in files if f.suffix == ".json" and f.parent.name == "data" and f.parent.parent.name == "assessment")
    pages = sorted(f for f in files if rel(f).startswith("about/") and f.name.endswith(".ar.html"))
    lessons = lesson_files(ar_md)

    baseline = json.loads(args.baseline.read_text(encoding="utf-8")) if args.baseline.exists() else {}
    floor = baseline.get("gloss_floor")
    densities = [gloss_density(f)[0] for f in lessons]
    if floor is None or args.reset_floor:
        lowest = min(densities) if densities else 0.0
        floor = max(0.0, math.floor((lowest - GLOSS_MARGIN) * 2) / 2)   # round down to 0.5

    violations = check_mermaid(ar_md) + check_dpo(ar_md, items, pages)
    gloss_v, gloss_rows = check_gloss(lessons, floor)
    violations += gloss_v

    if args.gloss_table:
        print(f"{'per 100':>8} {'glosses':>8} {'words':>7}  file")
        for d, g, w, f in gloss_rows:
            print(f"{d:8.1f} {g:8d} {w:7d}  {f}")
        print(f"floor {floor:g}")
        return 0

    print("Arabic rules (scripts/qa/arabic_rules.py)")
    print(f"  scanned {len(ar_md)} Arabic Markdown sources ({len(lessons)} lesson files), "
          f"{len(items)} self-assessment item files, {len(pages)} hand-written Arabic page(s)")
    print(f"  gloss floor {floor:g} per 100 Arabic words; lowest lesson today "
          f"{gloss_rows[0][0]:.1f} ({gloss_rows[0][3]})" if gloss_rows else "  no lesson files")

    if args.update_baseline:
        payload = {
            "about": "Written by scripts/qa/arabic_rules.py --update-baseline. Known exceptions are reported but do not "
                     "fail the run. See scripts/qa/README.md before adding to this list.",
            "gloss_floor": floor,
            "gloss_margin": GLOSS_MARGIN,
            "exceptions": sorted({v["key"] for v in violations}),
        }
        args.baseline.write_text(json.dumps(payload, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"\nBaseline written: {len(payload['exceptions'])} known exception(s), gloss floor {floor:g}")
        return 0

    known = set(baseline.get("exceptions", []))
    new = [v for v in violations if v["key"] not in known]
    old = [v for v in violations if v["key"] in known]
    fixed = sorted(known - {v["key"] for v in violations})
    for rule, title in (("mermaid", "Mermaid direction (LR in English → RL in Arabic)"),
                        ("dpo", f"DPO rendered with {PROTECTION}"),
                        ("gloss", "English glosses per 100 Arabic words")):
        vs = [v for v in violations if v["rule"] == rule]
        print(f"\n{title}: {len(vs)} violation(s)" + (f", {sum(v in new for v in vs)} new" if vs else ""))
        for v in vs:
            print(f"  {'NEW ' if v in new else 'known'} {v['where']}: {v['what']}")
    if fixed:
        print(f"\n{len(fixed)} known exception(s) are fixed; run --update-baseline to drop them:")
        for k in fixed:
            print(f"  - {k}")
    if new:
        print(f"\n✗ {len(new)} new violation(s) of the Arabic rules")
        return 1
    print(f"\n✓ no new violations ({len(old)} known exception(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
